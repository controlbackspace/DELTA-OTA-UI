"""The thesis data pack: one folder layout, one command.

    python -m sop.pack build   --root <sop-results> [--draft <CHAPTERS-4-AND-5-DRAFT.md>] [--base <v1.0.bin> --target <v1.1.bin>]
    python -m sop.pack publish --root <sop-results> --dest <testing-deliverables/thesis-data-pack>

Layout (under --root, normally `sop-results/`; the draft sits in the root, outside the three numbered folders):

    01-raw-data/         RUNS-INDEX.csv, RENAMES.csv, tidy-csv/ (analysis-ready CSVs), runs/ pilots/ discarded/ (the original run folders)
    02-interpretation/   tables/ (one .md per table) and figures/ (PNG)
    03-writing/          what the group writes Chapters 4 and 5 from: generated files (01_statistical-analysis.md, 07_baselines-results.md)
                         and hand-written ones (claims, limitations, scope, evidence map, failures, defense Q&A, reproducibility)

`build` regenerates only the generated files, the tidy CSVs, the table documents and the figures, and (with --draft) the Appendix of the
chapter draft. Runs are found through RUNS-INDEX.csv by run ID (R02 Table 4, R03 Table 2, R04 Table 3, R05 SOP 4 Web3, R06 baseline H,
R07 baseline N, R08 confirmation). `publish` copies the light parts (no raw evidence, no draft) to a tracked folder for the group.

Naming: numbered folders and writing files give a reading order; tables are `table-<n>_<slug>.md`, figures `fig-<nn>_<slug>.png`, tidy CSVs
`<table-or-topic>_<what>.csv`; dates appear only in run folder names.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import shutil
import tempfile
from pathlib import Path

from . import chapter4 as c4, figures, table_docs

RAW, INTERP, WRITING = "01-raw-data", "02-interpretation", "03-writing"
ROLE_BY_ID = {"cde": "R02", "ab": "R03", "t3": "R04", "web3": "R05", "h": "R06", "n": "R07", "confirm": "R08"}

TIDY_NAMES = {
    "ab_pairs.csv": "table2_ab-pairs.csv",
    "failures.csv": "table2_failures.csv",
    "table3_cycles.csv": "table3_gateway-cycles.csv",
    "scenarios_cde_trials.csv": "table4_cde-trials.csv",
    "baseline_n_pairs.csv": "baseline-n_a-vs-n-pairs.csv",
    "baseline_h_runs.csv": "baseline-h_https-runs.csv",
    "web3_checks.csv": "sop4_web3-checks.csv",
    "updater_heap_peak.csv": "sop4_updater-heap-peak.csv",
}
FIGURE_NAMES = {
    "fig1_payload.png": "fig-01_payload.png",
    "fig2_time_to_completion.png": "fig-02_time-to-completion.png",
    "fig3_completion_time_spread.png": "fig-03_completion-time-spread.png",
    "fig4_time_vs_repeated_requests.png": "fig-04_time-vs-repeated-requests.png",
    "fig5_ledger_check_and_ram.png": "fig-05_ledger-check-and-ram.png",
    "fig6_https_baseline.png": "fig-06_https-baseline.png",
    "fig7_security_tax.png": "fig-07_security-tax.png",
}
TABLE_FILES = {"1": "table-1_static-payload.md", "2": "table-2_hardware-network.md", "3": "table-3_gateway-profile.md",
               "4": "table-4_security-validation.md", "s2": "table-s2_baselines-h-n.md"}
# names used inside generated text -> where the content lives in this layout
TEXT_NAMES = {
    "`STATISTICS.md`": "`03-writing/01_statistical-analysis.md`",
    "`SOP-MAP-AND-CLAIMS.md`": "`03-writing/05_sop-evidence-map.md`",
    "`BASELINES-SPEC.md`": "`03-writing/06_baselines-spec.md`",
    "`BASELINES.md`": "`03-writing/07_baselines-results.md`",
    "`data/ab_pairs.csv`": "`01-raw-data/tidy-csv/table2_ab-pairs.csv`",
    "`data/failures.csv`": "`01-raw-data/tidy-csv/table2_failures.csv`",
    "`TABLES-1-AND-4.md`": "`02-interpretation/tables/`",
    "`TABLES-2-AND-3.md`": "`02-interpretation/tables/`",
}
GENERATED_MARK = "*Generated by `python -m sop.pack build`: do not edit by hand; rerun the command.*"


def _sha(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _names(text: str) -> str:
    for a, b in TEXT_NAMES.items():
        text = text.replace(a, b)
    return text


# ------------------------------------------------------------------------------------------------ index
def read_index(root: Path) -> list[dict]:
    with open(Path(root) / RAW / "RUNS-INDEX.csv", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def run_path(root: Path, run_id: str) -> Path:
    rows = [r for r in read_index(root) if r["run_id"] == run_id]
    if len(rows) != 1:
        raise KeyError(f"run {run_id} must appear exactly once in RUNS-INDEX.csv")
    return Path(root) / RAW / rows[0]["folder"]


def locate(root: Path) -> dict:
    """The run folders (and the Table 4 CSV) the analysis reads, found by run ID."""
    runs = {role: run_path(root, rid) for role, rid in ROLE_BY_ID.items() if role in ("ab", "t3", "web3", "h", "n", "confirm")}
    runs["cde_csv"] = run_path(root, ROLE_BY_ID["cde"]) / "campaign" / "trials.csv"
    return runs


# ------------------------------------------------------------------------------------------------ per-table documents
def _serves(intro: str, n: str) -> str:
    for line in intro.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 4 and cells[0] == n:
            return f"**Serves:** {cells[1]}. **Equation:** {cells[2]}. **Draft section:** {cells[3]}."
    return ""


def _title(section: str) -> str:
    line = next(l for l in section.splitlines() if l.startswith("**Table"))
    return line.strip("*")


def _wrap(title: str, serves: str, body: str) -> str:
    head = (f"# {title}\n\n*Approved Experiment Paper table: layout, headings and markers unchanged; only the cells are filled from recorded data.*\n"
            f"{GENERATED_MARK}\n\n{serves}\n\n")
    return head + body.strip() + "\n"


def split_table_docs(doc14: str, doc23: str) -> dict[str, str]:
    """The two combined documents of table_docs, cut into one document per approved table."""
    intro14, t1, t4 = doc14.split("\n---\n")
    i = doc23.index("\n## How to read Table 3")
    j = doc23.index("\n## How to read Table 2")
    intro23, t2, t3 = doc23[:j], doc23[j:i], doc23[i:]
    return {"1": _wrap(_title(t1), _serves(intro14, "1"), t1), "4": _wrap(_title(t4), _serves(intro14, "4"), t4),
            "2": _wrap(_title(t2), _serves(intro23, "2"), t2), "3": _wrap(_title(t3), _serves(intro23, "3"), t3)}


def s2_document(parts: dict) -> str:
    head = ("# Supplementary Table S2: the Chapter 3 comparators (HTTPS full binary H, naked-CoAP delta N)\n\n"
            "*Supplementary, **not** one of the approved Tables 1 to 4. Results and discussion: `03-writing/07_baselines-results.md`; specification: `03-writing/06_baselines-spec.md`.*\n"
            f"{GENERATED_MARK}\n\n")
    return head + parts["intro"].strip() + "\n\n" + parts["table"].strip() + "\n\n" + parts["provenance"].strip() + "\n"


# ------------------------------------------------------------------------------------------------ build
def _draw_figures(ctx: dict, found: dict, stage: Path) -> None:
    """Draw the figures in this interpreter, or, when matplotlib is missing here (the gateway virtual environment has none), with the
    Python found on PATH that has it."""
    try:
        import matplotlib  # noqa: F401
    except ImportError:
        import shutil as _sh
        import subprocess
        import sys

        for exe in (_sh.which("python"), _sh.which("py"), _sh.which("python3")):
            if exe and Path(exe).resolve() != Path(sys.executable).resolve():
                cmd = [exe, "-m", "sop.figures", "--ab", str(found["ab"]), "--t3", str(found["t3"]), "--cde", str(found["cde_csv"]),
                       "--web3", str(found["web3"]), "--n", str(found["n"]), "--h", str(found["h"]), "--out", str(stage)]
                r = subprocess.run(cmd, cwd=Path(__file__).resolve().parents[1], capture_output=True, text=True)
                if r.returncode == 0:
                    return
        raise SystemExit("matplotlib is required for the figures: install it, or run with --no-figures")
    figures.make_all(ctx, stage / "figures")


def build(root: Path, base: str | None = None, target: str | None = None, draft: Path | None = None, with_figures: bool = True) -> dict:
    root = Path(root).resolve()
    found = locate(root)
    ctx = c4.analyse(found["ab"], found["t3"], found["cde_csv"], found["web3"], found["n"], found["h"], found["confirm"])
    tidy, tables, figs, writing = root / RAW / "tidy-csv", root / INTERP / "tables", root / INTERP / "figures", root / WRITING
    for d in (tidy, tables, figs, writing):
        d.mkdir(parents=True, exist_ok=True)

    # statistics (generated, chapter-ready)
    (writing / "01_statistical-analysis.md").write_text(_names(c4.render(ctx)), encoding="utf-8")

    # tidy CSVs: exported to a staging folder by chapter4, then copied under the layout's names
    with tempfile.TemporaryDirectory() as stage:
        stage = Path(stage)
        c4.export(ctx, stage, stage)
        for old, new in TIDY_NAMES.items():
            src = stage / "data" / old if (stage / "data" / old).exists() else stage / old
            if src.exists():
                shutil.copyfile(src, tidy / new)
        if with_figures:
            _draw_figures(ctx, found, stage)
            for old, new in FIGURE_NAMES.items():
                if (stage / "figures" / old).exists():
                    shutil.copyfile(stage / "figures" / old, figs / new)
    manifest = [f"{_sha(p)}  {p.relative_to(tidy.parent)}".replace("\\", "/") for p in sorted(tidy.glob("*.csv"))]
    (tidy / "MANIFEST.sha256").write_text("\n".join(manifest) + "\n", encoding="utf-8")

    # tables: one document per approved table, plus Supplementary Table S2
    doc14, doc23, head = c4.table_documents(ctx, base, target)
    docs = split_table_docs(doc14, doc23)
    for n, text in docs.items():
        (tables / TABLE_FILES[n]).write_text(_names(text), encoding="utf-8")
    n_csv = next(Path(p) for name, p in ctx["inputs"] if name.startswith("Scenario N"))
    parts = table_docs.baselines_parts(ctx=ctx, n_csv=n_csv, h_dir=found["h"], head=head)
    (tables / TABLE_FILES["s2"]).write_text(_names(s2_document(parts)), encoding="utf-8")
    (writing / "07_baselines-results.md").write_text(_names(table_docs.baselines_results_doc(parts)), encoding="utf-8")
    if draft:
        c4.refresh_draft_appendix(Path(draft), doc14, doc23)
    return {"ctx": ctx, "tables": sorted(TABLE_FILES.values()), "tidy": sorted(p.name for p in tidy.glob("*.csv")), "head": head}


# ------------------------------------------------------------------------------------------------ publish
README_PACK = """# Thesis data pack (generated copy)

Light copy of `sop-results/` for writing Chapters 4 and 5: analysis-ready CSVs, one markdown file per table, the figures, and the chapter-ready writing files.
It does **not** contain the raw evidence (serial logs, packet captures, run folders), which stay with the person who ran the experiments (and in the archive zip).

| Folder | What | Start with |
|---|---|---|
| `03-writing/` | Statistical analysis, claims, limitations, scope, evidence map, baselines, failures, defense Q&A, reproducibility | `00_START-HERE.md` |
| `02-interpretation/` | `tables/` (one file per table) and `figures/` | `tables/table-2_hardware-network.md` |
| `01-raw-data/` | `RUNS-INDEX.csv` (what every run is), `tidy-csv/` (the CSVs behind every table), `RENAMES.csv` (old to new run names) | `tidy-csv/` |

Generated by `python -m sop.pack publish` from `sop-results/`. Do not edit here: change the source and publish again. The chapter draft is not part of this pack.
"""


def publish(root: Path, dest: Path) -> list[str]:
    root, dest = Path(root).resolve(), Path(dest).resolve()
    if dest.exists():
        shutil.rmtree(dest)
    copied = []
    (dest / RAW).mkdir(parents=True)
    for name in ("RUNS-INDEX.csv", "RENAMES.csv"):
        if (root / RAW / name).exists():
            shutil.copyfile(root / RAW / name, dest / RAW / name)
            copied.append(f"{RAW}/{name}")
    shutil.copytree(root / RAW / "tidy-csv", dest / RAW / "tidy-csv")
    shutil.copytree(root / INTERP, dest / INTERP)
    shutil.copytree(root / WRITING, dest / WRITING)
    (dest / "README.md").write_text(README_PACK, encoding="utf-8")
    return sorted(str(p.relative_to(dest)).replace("\\", "/") for p in dest.rglob("*") if p.is_file())


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="regenerate the generated files of the pack")
    b.add_argument("--root", required=True)
    b.add_argument("--draft", help="refresh the Appendix of this chapter draft")
    b.add_argument("--base")
    b.add_argument("--target")
    b.add_argument("--no-figures", action="store_true")
    p = sub.add_parser("publish", help="copy the light parts to a tracked folder")
    p.add_argument("--root", required=True)
    p.add_argument("--dest", required=True)
    a = ap.parse_args(argv)
    if a.cmd == "build":
        r = build(Path(a.root), a.base, a.target, Path(a.draft) if a.draft else None, not a.no_figures)
        print(f"built: {len(r['tables'])} table documents, {len(r['tidy'])} tidy CSVs (revision {r['head']})")
    else:
        files = publish(Path(a.root), Path(a.dest))
        print(f"published {len(files)} files to {a.dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
